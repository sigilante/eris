#!/usr/bin/env python3
"""Regenerate the Eris standalone Cargo workspace manifest for the nockvm subtree.

Eris isolates nockvm from the nockchain monorepo workspace entirely: instead of
letting Cargo resolve nockvm's `*.workspace = true` inheritance against
nockchain's 45-crate root Cargo.toml, we install our own workspace root at
`third_party/nockchain/crates/nockvm/Cargo.toml` that re-declares exactly the
`[workspace.package]` / `[workspace.lints]` / `[workspace.dependencies]` the
subtree inherits, with every version/feature lifted verbatim from the pinned
root. The nockvm crates then root at `crates/nockvm/`, not the monorepo.

This is the reconcile-on-bump tool: after bumping the nockchain submodule pin,
re-run this, then regenerate the patch (see patches/README.md) and log any dep
drift in CHANGES.md. Output is deterministic; a no-op run means no drift.

Usage:  patches/nockchain/regen-standalone-ws.py
(run from the Eris repo root; reads the pinned submodule, writes the manifest.)
"""
import tomllib, os, re, sys

ERIS = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
NC = os.path.join(ERIS, "third_party", "nockchain")
BASE = "crates/nockvm/rust"
# Subtree members, in the order upstream's nested-workspace.toml lists them.
MEMBERS = ["assert_no_alloc", "ibig", "nockvm", "nockvm_crypto",
           "nockvm_macros", "murmur3", "murmur3/murmur3-sys"]

root = tomllib.load(open(os.path.join(NC, "Cargo.toml"), "rb"))
ws = root["workspace"]
wsdeps = ws["dependencies"]

# Recompute the inherited-dep set from the actual member manifests every run, so
# dep drift (a member starting/stopping inheriting something) is picked up.
need = set()
present = []
for m in MEMBERS:
    p = os.path.join(NC, BASE, m, "Cargo.toml")
    if not os.path.exists(p):
        print(f"!! member missing at pin: {BASE}/{m}", file=sys.stderr)
        continue
    present.append(m)
    man = tomllib.load(open(p, "rb"))
    for sect in ("dependencies", "dev-dependencies", "build-dependencies"):
        for name, spec in man.get(sect, {}).items():
            if isinstance(spec, dict) and spec.get("workspace"):
                need.add(name)

missing = sorted(n for n in need if n not in wsdeps)
if missing:
    sys.exit(f"!! inherited deps absent from root workspace.dependencies: {missing}")


def tv(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "[" + ", ".join(tv(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {tv(val)}" for k, val in v.items()) + " }"
    raise TypeError(v)


def dep_line(name, spec):
    if isinstance(spec, dict) and "path" in spec:
        spec = dict(spec)
        spec["path"] = re.sub(r"^crates/nockvm/", "", spec["path"])  # repoint local
    return f"{name} = {tv(spec)}"


# Slice [workspace.lints.*] verbatim from the root text (preserves comments).
txt = open(os.path.join(NC, "Cargo.toml")).read().splitlines()
start = end = None
for i, l in enumerate(txt):
    if re.match(r"^\[workspace\.lints", l):
        if start is None:
            start = i
    elif start is not None and re.match(r"^\[", l) and not l.startswith("[workspace.lints"):
        end = i
        break
if end is None:
    end = len(txt)
lints = "\n".join(txt[start:end]).rstrip() if start is not None else ""

out = [
    "# GENERATED by patches/nockchain/regen-standalone-ws.py — do not hand-edit.",
    "# Eris standalone workspace manifest for the nockvm subtree, lifted verbatim",
    "# from the pinned nockchain root Cargo.toml (see PROVENANCE.md). Isolates",
    "# nockvm from the nockchain monorepo workspace. Reconcile on pin bump by",
    "# re-running the generator; log dep drift in CHANGES.md.",
    "",
    "[workspace]",
    'resolver = "2"',
    "members = [",
    *[f'    "rust/{m}",' for m in present],
    "]",
    "",
    "[workspace.package]",
    f'version = "{ws["package"]["version"]}"',
    f'edition = "{ws["package"]["edition"]}"',
    "",
    lints,
    "",
    "[workspace.dependencies]",
    *[dep_line(n, wsdeps[n]) for n in sorted(need)],
]
dest = os.path.join(NC, "crates", "nockvm", "Cargo.toml")
open(dest, "w").write("\n".join(out) + "\n")
print(f"wrote {dest}")
print(f"members: {len(present)}  inherited deps: {len(need)}")
